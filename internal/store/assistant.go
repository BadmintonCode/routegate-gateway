package store

import (
	"context"
	"database/sql"
	"strings"
	"time"
)

// AssistantSession is one chat thread owned by the admin user that created
// it. model_id = 0 means "use the current default model"; the
// user_id scoping is enforced in code (no FKs by design).
type AssistantSession struct {
	ID         int64
	SessionKey string
	UserID     int64
	UserName   string
	Title      string
	ModelID    int64
	CreatedAt  time.Time
	UpdatedAt  time.Time
}

// AssistantMessage is one chat row. Role is "user" or "assistant"; assistant
// rows carry a tool_calls JSON audit trail (the read-only invocations the
// model triggered) and the reasoning chain when the model exposes one.
type AssistantMessage struct {
	ID        int64
	Role      string
	Content   string
	Reasoning string
	ToolCalls []byte // raw JSON, nil when none
	CreatedAt time.Time
}

// CreateAssistantSession inserts one session with the caller-supplied random
// key (generated by the handler, not by the model).
func CreateAssistantSession(ctx context.Context, db *sql.DB, s AssistantSession) (int64, error) {
	res, err := db.ExecContext(ctx,
		`INSERT INTO assistant_sessions (session_key, user_id, user_name, title, model_id) VALUES (?, ?, ?, ?, ?)`,
		s.SessionKey, s.UserID, s.UserName, s.Title, s.ModelID)
	if err != nil {
		return 0, err
	}
	return res.LastInsertId()
}

// LoadAssistantSessionByKey reads one session by its public key.
func LoadAssistantSessionByKey(ctx context.Context, db *sql.DB, key string) (AssistantSession, error) {
	var s AssistantSession
	var created, updated sql.NullTime
	err := db.QueryRowContext(ctx,
		`SELECT id, session_key, user_id, user_name, title, model_id, created_at, updated_at
		 FROM assistant_sessions WHERE session_key = ?`, key).
		Scan(&s.ID, &s.SessionKey, &s.UserID, &s.UserName, &s.Title, &s.ModelID, &created, &updated)
	if err != nil {
		return AssistantSession{}, err
	}
	s.CreatedAt, s.UpdatedAt = created.Time, updated.Time
	return s, nil
}

// ListAssistantSessions returns the user's sessions, newest activity first.
func ListAssistantSessions(ctx context.Context, db *sql.DB, userID int64, limit int) ([]AssistantSession, error) {
	if limit <= 0 || limit > 200 {
		limit = 200
	}
	rows, err := db.QueryContext(ctx,
		`SELECT id, session_key, user_id, user_name, title, model_id, created_at, updated_at
		 FROM assistant_sessions WHERE user_id = ? ORDER BY updated_at DESC, id DESC LIMIT ?`, userID, limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []AssistantSession
	for rows.Next() {
		var s AssistantSession
		var created, updated sql.NullTime
		if err := rows.Scan(&s.ID, &s.SessionKey, &s.UserID, &s.UserName, &s.Title, &s.ModelID, &created, &updated); err != nil {
			continue
		}
		s.CreatedAt, s.UpdatedAt = created.Time, updated.Time
		out = append(out, s)
	}
	return out, rows.Err()
}

// UpdateSessionMeta sets the title and/or model selection inside the caller's
// transaction.
func UpdateSessionMeta(ctx context.Context, tx *sql.Tx, id int64, title string, modelID int64) error {
	res, err := tx.ExecContext(ctx,
		`UPDATE assistant_sessions SET title = ?, model_id = ? WHERE id = ?`, title, modelID, id)
	if err != nil {
		return err
	}
	if n, err := res.RowsAffected(); err != nil {
		return err
	} else if n == 0 {
		return sql.ErrNoRows
	}
	return nil
}

// TouchAssistantSession records recent activity without changing the title or
// endpoint selection. It keeps the session list ordered by the latest turn.
func TouchAssistantSession(ctx context.Context, db *sql.DB, id int64) error {
	res, err := db.ExecContext(ctx,
		`UPDATE assistant_sessions SET updated_at = CURRENT_TIMESTAMP WHERE id = ?`, id)
	if err != nil {
		return err
	}
	if n, err := res.RowsAffected(); err != nil {
		return err
	} else if n == 0 {
		return sql.ErrNoRows
	}
	return nil
}

// DeleteAssistantSession removes the session and its messages atomically.
func DeleteAssistantSession(ctx context.Context, db *sql.DB, id int64) error {
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err := tx.ExecContext(ctx, `DELETE FROM assistant_messages WHERE session_id = ?`, id); err != nil {
		return err
	}
	res, err := tx.ExecContext(ctx, `DELETE FROM assistant_sessions WHERE id = ?`, id)
	if err != nil {
		return err
	}
	if _, err := res.RowsAffected(); err != nil {
		return err
	}
	return tx.Commit()
}

// AppendAssistantMessage stores one chat row and returns its id. reasoning is
// the model's thinking chain ("" = none); toolCalls JSON is nil for user rows.
func AppendAssistantMessage(ctx context.Context, db *sql.DB, sessionID int64, role, content, reasoning string, toolCalls []byte) (int64, error) {
	res, err := db.ExecContext(ctx,
		`INSERT INTO assistant_messages (session_id, role, content, reasoning, tool_calls) VALUES (?, ?, ?, ?, ?)`,
		sessionID, role, content, nullIfEmpty(reasoning), toolCalls)
	if err != nil {
		return 0, err
	}
	return res.LastInsertId()
}

// nullIfEmpty maps empty strings to SQL NULL so reasoning/tool_calls columns
// stay clearly "absent" rather than empty values.
func nullIfEmpty(s string) any {
	if strings.TrimSpace(s) == "" {
		return nil
	}
	return s
}

// ListAssistantMessages reads the session history in insertion order. limit
// bounds the most recent tail (0 = all).
func ListAssistantMessages(ctx context.Context, db *sql.DB, sessionID int64, limit int) ([]AssistantMessage, error) {
	query := `SELECT id, role, content, reasoning, tool_calls, created_at FROM assistant_messages`
	var args []any
	if limit > 0 {
		// The inner ORDER BY picks the newest tail; the outer ASC restores
		// chronological order for the model context.
		query += ` WHERE id IN (SELECT id FROM (SELECT id FROM assistant_messages WHERE session_id = ? ORDER BY id DESC LIMIT ?) t)`
		args = []any{sessionID, limit}
	} else {
		query += ` WHERE session_id = ?`
		args = []any{sessionID}
	}
	query += ` ORDER BY id ASC`
	rows, err := db.QueryContext(ctx, query, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []AssistantMessage
	for rows.Next() {
		var m AssistantMessage
		var created sql.NullTime
		var reasoning sql.NullString
		// NULL scans as a nil []byte, so tool_calls absence needs no wrapper.
		if err := rows.Scan(&m.ID, &m.Role, &m.Content, &reasoning, &m.ToolCalls, &created); err != nil {
			continue
		}
		m.Reasoning = reasoning.String
		m.CreatedAt = created.Time
		out = append(out, m)
	}
	return out, rows.Err()
}
