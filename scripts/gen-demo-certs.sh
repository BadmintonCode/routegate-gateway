#!/usr/bin/env bash
# Generate demo certificates for the RouteGate quickstart (ADR-0001 §6.3.2
# source A: pinned leaf certificates; in production the panel generates or
# uploads these). Also emits deploy/demo-seed.sql with the certificate public
# material registered as identities, routes, and policies.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/deploy/certs"
SEED="$ROOT/deploy/demo-seed.sql"

mkdir -p "$OUT"

gen_cert() { # name cn uri-san
  local name="$1" cn="$2" uri="$3"
  if [ -s "$OUT/$name.crt" ] && [ -s "$OUT/$name.key" ]; then
    echo "keep existing $name"
    return
  fi
  openssl ecparam -name prime256v1 -genkey -noout -out "$OUT/$name.key" 2>/dev/null
  openssl req -new -x509 -key "$OUT/$name.key" -out "$OUT/$name.crt" -days 90 \
    -subj "/CN=$cn" -addext "subjectAltName=URI:$uri" 2>/dev/null
  echo "generated $name (90 days, ECDSA P-256)"
}

# Gateway server cert: SAN covers in-mesh DNS name plus host loopback for curl.
if [ ! -s "$OUT/gateway.crt" ]; then
  openssl ecparam -name prime256v1 -genkey -noout -out "$OUT/gateway.key" 2>/dev/null
  openssl req -new -x509 -key "$OUT/gateway.key" -out "$OUT/gateway.crt" -days 90 \
    -subj "/CN=routegate" \
    -addext "subjectAltName=DNS:routegate,DNS:localhost,IP:127.0.0.1" 2>/dev/null
  echo "generated gateway server cert"
fi

# Caller/workload identities. URI SANs exercise the name-consistency check.
gen_cert caller demo-caller "https://routegate.local/identities/demo-caller"
gen_cert alpha  demo-alpha  "https://routegate.local/identities/demo-alpha"
gen_cert beta   demo-beta   "https://routegate.local/identities/demo-beta"
gen_cert edge   demo-edge   "https://routegate.local/identities/demo-edge"

pem_oneline() { # indent PEM into SQL string continuation
  sed 's/$/\\n/' "$1" | tr -d '\n'
}

NOW_SQL="$(date -u '+%Y-%m-%d %H:%M:%S')"
EXPIRY_SQL="$(date -u -v+30d '+%Y-%m-%d %H:%M:%S' 2>/dev/null || date -u -d '+30 days' '+%Y-%m-%d %H:%M:%S')"

caller_pem="$(pem_oneline "$OUT/caller.crt")"
alpha_pem="$(pem_oneline "$OUT/alpha.crt")"
beta_pem="$(pem_oneline "$OUT/beta.crt")"
edge_pem="$(pem_oneline "$OUT/edge.crt")"

cat > "$SEED" <<SQL
-- RouteGate demo seed (generated by scripts/gen-demo-certs.sh).
-- Apply with: docker exec -i routegate-mysql mysql -uroot -proot-demo routegate < deploy/demo-seed.sql
-- Direct DB edits do NOT propagate by themselves: the trailing UPDATE bumps
-- config_revision (the same thing \`routegate config bump\` does).

-- Identities: pinned leaf certificates (public material only; keys never leave the demo files).
DELETE FROM identities WHERE name IN ('demo-caller','demo-alpha','demo-beta','demo-edge');
INSERT INTO identities (name, key_id, credential_type, public_material, source, status, not_before, not_after, created_by, remark) VALUES
('demo-caller', 'demo-seed', 'mtls_cert', '${caller_pem}', 'upload', 'active', '${NOW_SQL}', '${EXPIRY_SQL}', 0, 'quickstart caller'),
('demo-alpha',  'demo-seed', 'mtls_cert', '${alpha_pem}',  'upload', 'active', '${NOW_SQL}', '${EXPIRY_SQL}', 0, 'quickstart upstream alpha'),
('demo-beta',   'demo-seed', 'mtls_cert', '${beta_pem}',   'upload', 'active', '${NOW_SQL}', '${EXPIRY_SQL}', 0, 'quickstart upstream beta'),
('demo-edge',   'demo-seed', 'mtls_cert', '${edge_pem}',   'upload', 'active', '${NOW_SQL}', '${EXPIRY_SQL}', 0, 'quickstart public edge caller');

-- Routes: /alpha and /beta strip their prefix before reaching upstreams.
DELETE FROM policies;
DELETE FROM routes;
INSERT INTO routes (name, path_prefix, methods, targets, strip_prefix, enabled, remark) VALUES
('demo-alpha', '/alpha', NULL, '[{"host":"demo-alpha","port":8080,"weight":1}]', 1, 1, 'quickstart upstream alpha'),
('demo-beta',  '/beta',  NULL, '[{"host":"demo-beta","port":8080,"weight":1}]',  1, 1, 'quickstart upstream beta');

-- Registered operations of each route (policy editor picks from these).
INSERT INTO route_operations (route_id, method, path, name)
SELECT id, 'GET', '/v1/**',   'alpha reads'  FROM routes WHERE name = 'demo-alpha';
INSERT INTO route_operations (route_id, method, path, name)
SELECT id, 'GET', '/admin/**', 'alpha admin' FROM routes WHERE name = 'demo-alpha';
INSERT INTO route_operations (route_id, method, path, name)
SELECT id, 'GET', '/v1/**',   'beta reads'   FROM routes WHERE name = 'demo-beta';

-- Policies: deny > allow > default deny.
-- demo-caller may read /v1/** on alpha and beta; /admin/** is explicitly denied;
-- everything else falls through to default deny.
INSERT INTO policies (route_id, caller, method, path_pattern, effect, enabled, created_by, remark)
SELECT id, 'demo-caller', 'GET', '/admin/**', 'deny', 1, 0, 'explicit deny beats allow'
FROM routes WHERE name = 'demo-alpha';
INSERT INTO policies (route_id, caller, method, path_pattern, effect, enabled, created_by, remark)
SELECT id, 'demo-caller', 'GET', '/v1/**', 'allow', 1, 0, 'caller reads both services'
FROM routes WHERE name IN ('demo-alpha','demo-beta');
INSERT INTO policies (route_id, caller, method, path_pattern, effect, enabled, created_by, remark)
SELECT id, 'demo-alpha', 'GET', '/v1/**', 'allow', 1, 0, 'service-to-service: alpha reads beta'
FROM routes WHERE name = 'demo-beta';
INSERT INTO policies (route_id, caller, method, path_pattern, effect, enabled, created_by, remark)
SELECT id, 'demo-edge', 'GET', '/v1/**', 'allow', 1, 0, 'edge public alpha API'
FROM routes WHERE name = 'demo-alpha';
INSERT INTO policies (route_id, caller, method, path_pattern, effect, enabled, created_by, remark)
SELECT id, 'demo-edge', 'GET', '/admin/**', 'deny', 1, 0, 'edge public admin deny'
FROM routes WHERE name = 'demo-alpha';
INSERT INTO policies (route_id, caller, method, path_pattern, effect, enabled, created_by, remark)
SELECT id, 'demo-edge', 'GET', '/v1/**', 'allow', 1, 0, 'edge public beta API'
FROM routes WHERE name = 'demo-beta';

-- Debug logging (ADR-0001 §6.6): on by default in the demo, maintained in the
-- panel 设置 page (settings.debug_log). The path matches the compose mount.
INSERT INTO settings (name, value) VALUES ('debug_log', CAST('{\"enabled\":true,\"file\":\"/var/log/routegate/debug.log\",\"max_mb\":1,\"retain_days\":7,\"request_body_max_bytes\":65536,\"response_body_max_bytes\":65536,\"headers_max_bytes\":32768,\"queue_capacity\":1024}' AS JSON))
ON DUPLICATE KEY UPDATE value = VALUES(value);

-- Bump the revision so every gateway instance reloads within one sync tick.
UPDATE settings SET value = CAST(CAST(JSON_EXTRACT(value,'$') AS UNSIGNED) + 1 AS JSON) WHERE name = 'config_revision';
SQL

echo "seed written: $SEED"
